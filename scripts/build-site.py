#!/usr/bin/env python3
"""Generate 65 static problem pages. Setup and commands: scripts/build-site.md."""

import argparse
from pathlib import Path
import sys

from generate_manifest import DEFAULT_ROOT, ManifestError, generate_manifest, render_manifest
from site_renderer import SITE_FILES, render_page


GENERATED_MARKER = b"<!-- Generated by scripts/build-site.py; edit Markdown sources. -->"


def build_files(root):
    """Validate the manifest before consuming its public schema."""
    manifest = generate_manifest(root)
    if (root / "scripts/problem-manifest.json").read_bytes() != render_manifest(manifest).encode("utf-8"):
        raise ValueError("manifest is stale; run python3 scripts/generate_manifest.py")
    pages = {problem["source_path"]: problem["slug"] for problem in manifest["problems"]}
    files = {
        Path("problems") / (problem["slug"] + ".html"): render_page(problem, root, pages).encode("utf-8")
        for problem in manifest["problems"]
    }
    files[Path("renderer/mermaid.mjs")] = (SITE_FILES / "mermaid.mjs").read_bytes()
    return files


def build_site(root, output, check=False):
    files = build_files(root)
    stale = sorted(path for path in (output / "problems").glob("*.html") if path.relative_to(output) not in files)
    # Only remove pages this generator owns; leave adjacent site work untouched.
    for path in stale:
        if not path.read_bytes().startswith(GENERATED_MARKER):
            raise ValueError(f"unexpected unowned page: {path}")
    if check:
        differences = [str(path) for path, content in files.items() if not (output / path).is_file() or (output / path).read_bytes() != content]
        differences.extend(str(path.relative_to(output)) for path in stale)
        if differences:
            raise ValueError("generated site missing or stale: " + ", ".join(differences))
    else:
        for path, content in files.items():
            destination = output / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(content)
        for path in stale:
            path.unlink()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=DEFAULT_ROOT, help="repository root")
    parser.add_argument("--output", type=Path, help="site directory (default: <root>/docs)")
    parser.add_argument("--check", action="store_true", help="fail for missing or stale output without writing")
    args = parser.parse_args()
    root = args.root.resolve()
    output = args.output.resolve() if args.output else root / "docs"
    try:
        build_site(root, output, args.check)
    except (ManifestError, OSError, ValueError) as error:
        print(f"Site error: {error}", file=sys.stderr)
        return 1
    print(f"{'Site current' if args.check else 'Built site'}: 65 problem pages")
    return 0


if __name__ == "__main__":
    sys.exit(main())
